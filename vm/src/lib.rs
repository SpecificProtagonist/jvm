/// An implementation for a native method.
pub struct NativeMethod {
    pub class: String,
    pub method: String,
    pub args: Vec<Type>,
    pub returns: Option<Type>,
    bind: Box<dyn Fn(&method::Method) -> Result<(), NativeBindError> + Send + Sync>,
}

impl Debug for NativeMethod {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("NativeMethod")
            .field("class", &self.class)
            .field("args", &self.args)
            .field("returns", &self.returns)
            .finish()
    }
}

impl NativeMethod {
    pub fn new<N>(
        class: impl Into<String>,
        method: impl Into<String>,
        args: impl Into<Vec<Type>>,
        returns: impl Into<Option<Type>>,
        native: impl NativeFn<N> + Copy,
    ) -> Self {
        Self {
            class: class.into(),
            method: method.into(),
            args: args.into(),
            returns: returns.into(),
            bind: Box::new(move |method| fake_variadics::bind_native_code(method, native)),
        }
    }

    /// Makes this method available to its class.
    ///
    /// This doesn't cause the method's class to get loaded if it isn't.
    /// Because of this, no errors are returned if the methods mismatch.
    pub fn make_available(self, jvm: &Jvm) {
        let mut lock = jvm.deref().unbound_native_methods.lock().unwrap();
        let entry = lock
            .entry_ref(&self.class)
            .or_insert(UnboundNativeMethods::Available(Vec::new()));
        match entry {
            UnboundNativeMethods::Available(native_methods) => native_methods.push(self),
            UnboundNativeMethods::ClassAlreadyInitialized => {
                let class = jvm.deref().resolve_class_internal(&self.class).unwrap();
                if let Some(method) = class.method(&self.method, self.args, self.returns) {
                    let _ = (self.bind)(method);
                }
            }
        }
    }

    /// Loads the method's class and binds the method.
    ///
    /// # Panics
    /// Panics if it couldn't be found or doesn't match.
    pub fn bind(&self, jvm: &Jvm) {
        let fail = || {
            panic!(
                "Failed to bind native method {}:{}",
                self.class, self.method
            )
        };
        let method = jvm
            .resolve_method(
                &self.class,
                &self.method,
                self.args.iter().cloned(),
                self.returns.clone(),
            )
            .unwrap_or_else(|_| fail());
        if (self.bind)(method.value).is_err() {
            fail();
        }
    }
}

/// Tells the vm how to interact with the class library.
pub struct ClassLibraryIntegration {
    /// Map from class name to layout of custom per-object metadata.
    ///
    /// See [`Jvm::define_object_metadata_layout`].
    pub metatada_layout: HashMap<String, Layout>,
    /// Implementation of native methods.
    ///
    /// See [NativeMethod::make_available].
    pub native_methods: Vec<NativeMethod>,
    /// Constructs a `java.lang.String` instance representing the given string.
    pub string_constructor: Box<dyn Fn(&Jvm, &str) -> Object + Send + Sync>,
}

impl Default for ClassLibraryIntegration {
    fn default() -> Self {
        Self {
            metatada_layout: default(),
            native_methods: default(),
            string_constructor: Box::new(|_, _| unimplemented!()),
        }
    }
}
